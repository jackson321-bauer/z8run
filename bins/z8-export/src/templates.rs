//! Templates for the generated `src/main.rs`.
//!
//! The generated glue only wires a trigger to the real `z8run-core` engine
//! (path dependency). No node logic is reproduced here.

/// Shared prelude used by both modes.
const PRELUDE: &str = r#"//! Generated by z8-export. Wiring only — the flow runs on z8run-core.
use std::collections::HashMap;
use std::sync::Arc;

use serde_json::Value;
use uuid::Uuid;
use z8run_core::canvas::{
    canvas_to_flow, hook_trigger_message, hook_trigger_payload, restrict_to_trigger,
};
use z8run_core::nodes::http_out::{
    init_webhook_responders, WebhookResponders,
};
use z8run_core::{Flow, FlowEngine};

const FLOW_JSON: &str = include_str!("../flow.json");
const CONFIGS: &[(&str, &str)] = &[
__CONFIGS__
];

type BoxErr = Box<dyn std::error::Error + Send + Sync>;

fn resolve_env(v: &Value) -> Result<Value, BoxErr> {
    match v {
        Value::String(s) if s.starts_with("vault:") => {
            let key = &s[6..];
            let var = format!(
                "Z8_SECRET_{}",
                key.to_ascii_uppercase()
                    .replace(|c: char| !c.is_ascii_alphanumeric(), "_")
            );
            std::env::var(&var)
                .map(Value::String)
                .map_err(|_| format!("secret '{key}' missing: set {var}").into())
        }
        Value::String(s) if s.starts_with("$ENV:") => {
            let var = &s[5..];
            std::env::var(var)
                .map(Value::String)
                .map_err(|_| format!("environment variable '{var}' is not set").into())
        }
        Value::Object(m) => {
            let mut out = m.clone();
            for (_k, val) in out.iter_mut() {
                *val = resolve_env(val)?;
            }
            Ok(Value::Object(out))
        }
        Value::Array(a) => {
            let mut out = Vec::with_capacity(a.len());
            for val in a {
                out.push(resolve_env(val)?);
            }
            Ok(Value::Array(out))
        }
        other => Ok(other.clone()),
    }
}

fn compile_one(stored: &Flow, canvas_id: &str) -> Result<(Flow, Uuid), BoxErr> {
    let (mut flow, id_map) = canvas_to_flow(stored)?;
    for (id, raw) in CONFIGS {
        let id: Uuid = id.parse()?;
        let cfg: Value = serde_json::from_str(raw)?;
        if let Some(node) = flow.nodes.iter_mut().find(|n| n.id == id) {
            node.config = resolve_env(&cfg)?;
        }
    }
    let trigger = *id_map
        .get(canvas_id)
        .ok_or_else(|| format!("trigger node '{canvas_id}' missing"))?;
    restrict_to_trigger(&mut flow, trigger);
    Ok((flow, trigger))
}

const TIMEOUT_SECS: u64 = 120;

async fn new_engine() -> Arc<FlowEngine> {
    let engine = Arc::new(FlowEngine::new());
    z8run_core::nodes::register_builtin_nodes(&engine).await;
    engine
}
"#;

/// CLI runner: stdin → flow → stdout, exit code from the error field.
pub const CLI_MAIN: &str = r#"
const TRIGGER_CANVAS_ID: &str = "__TRIGGER_CANVAS_ID__";
const TRIGGER_METHOD: &str = "__TRIGGER_METHOD__";
const TRIGGER_PATH: &str = "__TRIGGER_PATH__";

fn read_stdin_body() -> Result<Value, BoxErr> {
    let mut raw = String::new();
    std::io::Read::read_to_string(&mut std::io::stdin(), &mut raw)?;
    let t = raw.trim();
    if t.is_empty() {
        return Ok(Value::Null);
    }
    Ok(serde_json::from_str(t).unwrap_or_else(|_| Value::String(t.to_string())))
}

#[tokio::main]
async fn main() {
    if let Err(e) = run().await {
        eprintln!("z8-export: {e}");
        std::process::exit(1);
    }
}

async fn run() -> Result<(), BoxErr> {
    let stored: Flow = serde_json::from_str(FLOW_JSON)?;
    let (flow, _trigger) = compile_one(&stored, TRIGGER_CANVAS_ID)?;

    let responders: WebhookResponders = Arc::new(tokio::sync::RwLock::new(HashMap::new()));
    init_webhook_responders(responders.clone());
    let engine = new_engine().await;

    let body = read_stdin_body()?;
    let trace = Uuid::now_v7();
    let payload = hook_trigger_payload(
        TRIGGER_METHOD,
        TRIGGER_PATH,
        Value::Object(Default::default()),
        Value::Object(Default::default()),
        body,
    );
    let msg = hook_trigger_message(payload, trace);

    let (tx, rx) = tokio::sync::oneshot::channel();
    responders.write().await.insert(trace, tx);
    engine.execute_with_trigger(flow, Some(msg)).await?;

    let resp = match tokio::time::timeout(std::time::Duration::from_secs(TIMEOUT_SECS), rx).await {
        Ok(Ok(r)) => r,
        _ => {
            responders.write().await.remove(&trace);
            return Err("flow produced no response (no http-out reached)".into());
        }
    };

    let failed =
        resp.status >= 400 || resp.body.get("error").map(|e| !e.is_null()).unwrap_or(false);
    println!("{}", serde_json::to_string(&resp.body)?);
    if failed {
        std::process::exit(1);
    }
    Ok(())
}
"#;

/// Server runner: mini-axum with one route per trigger.
pub const SERVER_MAIN: &str = r#"
const ROUTES: &[(&str, &str)] = &[
__ROUTES__
];
const TRIGGER_IDS: &[&str] = &[
__TRIGGER_IDS__
];

#[derive(Clone)]
struct AppState {
    engine: Arc<FlowEngine>,
    flows: Arc<Vec<Flow>>,
    responders: WebhookResponders,
}

async fn handle(st: AppState, idx: usize, req: axum::extract::Request) -> axum::response::Response {
    use axum::response::IntoResponse;
    match run_one(&st, idx, req).await {
        Ok((status, body)) => (status, axum::Json(body)).into_response(),
        Err(e) => (
            axum::http::StatusCode::INTERNAL_SERVER_ERROR,
            axum::Json(serde_json::json!({"error": format!("{e}")})),
        )
            .into_response(),
    }
}

fn parse_query(q: &str) -> Value {
    let mut map = serde_json::Map::new();
    for pair in q.split('&').filter(|p| !p.is_empty()) {
        let (k, v) = pair.split_once('=').unwrap_or((pair, ""));
        let key = urlencoding::decode(k).map(|s| s.into_owned()).unwrap_or_else(|_| k.to_string());
        let val = urlencoding::decode(v).map(|s| s.into_owned()).unwrap_or_else(|_| v.to_string());
        map.insert(key, Value::String(val));
    }
    Value::Object(map)
}

async fn run_one(
    st: &AppState,
    idx: usize,
    req: axum::extract::Request,
) -> Result<(axum::http::StatusCode, Value), BoxErr> {
    let (parts, body) = req.into_parts();
    let method = parts.method.to_string();
    let expected = ROUTES[idx].0;
    if expected != "*" && !expected.eq_ignore_ascii_case(&method) {
        return Ok((
            axum::http::StatusCode::METHOD_NOT_ALLOWED,
            serde_json::json!({"error": "method not allowed"}),
        ));
    }

    let bytes = axum::body::to_bytes(body, 16 * 1024 * 1024).await?;
    let raw = String::from_utf8_lossy(&bytes).to_string();
    let body_json = if raw.trim().is_empty() {
        Value::Null
    } else {
        serde_json::from_str(&raw).unwrap_or(Value::String(raw))
    };

    let mut headers = serde_json::Map::new();
    for (name, value) in parts.headers.iter() {
        if let Ok(v) = value.to_str() {
            headers.insert(name.to_string(), Value::String(v.to_string()));
        }
    }
    let query = parts.uri.query().map(parse_query).unwrap_or_else(|| serde_json::json!({}));

    let trace = Uuid::now_v7();
    let payload = hook_trigger_payload(
        method,
        parts.uri.path().to_string(),
        Value::Object(headers),
        query,
        body_json,
    );
    let msg = hook_trigger_message(payload, trace);

    let (tx, rx) = tokio::sync::oneshot::channel();
    st.responders.write().await.insert(trace, tx);
    st.engine
        .execute_with_trigger(st.flows[idx].clone(), Some(msg))
        .await?;

    let resp = match tokio::time::timeout(std::time::Duration::from_secs(TIMEOUT_SECS), rx).await {
        Ok(Ok(r)) => r,
        _ => {
            st.responders.write().await.remove(&trace);
            return Err("flow produced no response (no http-out reached)".into());
        }
    };
    let status = axum::http::StatusCode::from_u16(resp.status)
        .unwrap_or(axum::http::StatusCode::OK);
    Ok((status, resp.body))
}

__HANDLERS__

#[tokio::main]
async fn main() {
    if let Err(e) = run().await {
        eprintln!("z8-export: {e}");
        std::process::exit(1);
    }
}

async fn run() -> Result<(), BoxErr> {
    let stored: Flow = serde_json::from_str(FLOW_JSON)?;
    let mut flows = Vec::with_capacity(TRIGGER_IDS.len());
    for id in TRIGGER_IDS {
        let (flow, _) = compile_one(&stored, id)?;
        flows.push(flow);
    }

    let responders: WebhookResponders = Arc::new(tokio::sync::RwLock::new(HashMap::new()));
    init_webhook_responders(responders.clone());
    let engine = new_engine().await;
    let state = AppState {
        engine,
        flows: Arc::new(flows),
        responders,
    };

    let mut router = axum::Router::new();
__ROUTE_REGISTRATION__
    let router = router.with_state(state);

    let bind = std::env::var("Z8_EXPORT_BIND").unwrap_or_else(|_| "127.0.0.1:8080".to_string());
    let listener = tokio::net::TcpListener::bind(&bind).await?;
    eprintln!("z8-export: listening on http://{bind}");
    axum::serve(listener, router).await?;
    Ok(())
}
"#;

pub fn cli_main(configs: &str, canvas_id: &str, method: &str, path: &str) -> String {
    let body = PRELUDE.replace("__CONFIGS__", configs) + CLI_MAIN;
    body.replace("__TRIGGER_CANVAS_ID__", canvas_id)
        .replace("__TRIGGER_METHOD__", method)
        .replace("__TRIGGER_PATH__", path)
}

pub fn server_main(
    configs: &str,
    routes: &str,
    trigger_ids: &str,
    route_registration: &str,
    handlers: &str,
) -> String {
    (PRELUDE.replace("__CONFIGS__", configs) + SERVER_MAIN)
        .replace("__ROUTES__", routes)
        .replace("__TRIGGER_IDS__", trigger_ids)
        .replace("__ROUTE_REGISTRATION__", route_registration)
        .replace("__HANDLERS__", handlers)
}
